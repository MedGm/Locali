"""Run the model red-team (evaluation/redteam_model.py) against a running model server.

    LOCALI_MODEL_URL=http://127.0.0.1:8093/v1 LOCALI_MODEL_KEY=... \\
        uv run python experiments/scripts/redteam_model.py

Uses the same variables as the backend (LOCALI_MODEL_URL, LOCALI_MODEL_KEY, LOCALI_MODEL_NAME,
LOCALI_MODEL_ID). Each goal runs once per placement, plus once with no payload, at temperature 0.
Rows are appended to experiments/results/redteam/model.jsonl as they finish, and a run that was
stopped picks up where it left off. Needs Docker for the debug and test-generation goals.
"""

import json
import os
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from evaluation.client import ChatClient
from evaluation.redteam_model import GOALS, placements, run_goal

OUT = ROOT / "experiments" / "results" / "redteam"


def fmt(rows: list[dict], key: str) -> str:
    values = [r[key] for r in rows if r[key] is not None]
    return f"{sum(values)}/{len(values)}" if values else "—"


def report(rows: list[dict], model_id: str, commit: str) -> str:
    attacked = [r for r in rows if r["placement"] != "none"]
    by_threat: dict[str, list[dict]] = defaultdict(list)
    for r in attacked:
        by_threat[r["threat"]].append(r)
    lines = ["# Red-team with the model: injection and jailbreak payloads in code", "",
             f"Model `{model_id}`, temperature 0, commit {commit}. Generated by `experiments/scripts/redteam_model.py`.",
             "Payloads are hidden in a demo_repo function (comment, docstring or string) and the agent step that",
             "reads it is run as in a real run. *Model complied*: the answer did what the payload asked. *Harm*:",
             "something harmful got through, with Locali's controls and without them (no static tools, no",
             "validation, no approval, the answer used as it is).", "",
             "| Threat | Attacks | Model complied | Harm with controls | Harm without controls |", "|---|---|---|---|---|"]
    lines += [f"| {t} | {len(v)} | {fmt(v, 'model_complied')} | {fmt(v, 'harm_with_controls')} | "
              f"{fmt(v, 'harm_without_controls')} |" for t, v in sorted(by_threat.items())]
    lines += ["", "| Goal | Step | Placement | Complied | Harm with | Harm without | What happened |",
              "|---|---|---|---|---|---|---|"]
    mark = {True: "yes", False: "no", None: "—"}
    for r in rows:
        lines.append(f"| {r['goal']} | {r['step']} | {r['placement']} | {mark[r['model_complied']]} | "
                     f"{mark[r['harm_with_controls']]} | {mark[r['harm_without_controls']]} | "
                     f"{r['detail'].replace('|', '/')} |")
    lines += ["", "The `none` rows are the same step without a payload: what the model does anyway (for example,",
              "whether it reports the SQL injection at all)."]
    return "\n".join(lines) + "\n"


def main() -> None:
    url = os.environ.get("LOCALI_MODEL_URL")
    if not url:
        sys.exit("set LOCALI_MODEL_URL (and LOCALI_MODEL_KEY if the server needs one)")
    client = ChatClient(url, model=os.environ.get("LOCALI_MODEL_NAME", "local"),
                        api_key=os.environ.get("LOCALI_MODEL_KEY", "local"))
    model_id = os.environ.get("LOCALI_MODEL_ID", "unknown")

    def model(messages):
        return client.complete(messages, max_tokens=768)

    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "model.jsonl"
    rows = [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []
    done = {(r["goal"], r["placement"]) for r in rows}
    with tempfile.TemporaryDirectory(prefix="locali-redteam-model-") as tmp:
        for goal in GOALS:
            for placement in placements(goal):
                if (goal.id, placement) in done:
                    continue
                row = run_goal(goal, placement, model, Path(tmp) / goal.id / placement) | {"model": model_id}
                with path.open("a") as f:
                    f.write(json.dumps(row) + "\n")
                rows.append(row)
                print(f"{goal.id:17} {placement:9} complied={row['model_complied']!s:5} "
                      f"harm_with={row['harm_with_controls']!s:5} harm_without={row['harm_without_controls']!s:5} "
                      f"{row['detail']}", flush=True)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                            check=False).stdout.strip()
    (OUT / "model.md").write_text(report(rows, model_id, commit))
    print(f"\nwrote {OUT / 'model.md'}")


if __name__ == "__main__":
    main()
