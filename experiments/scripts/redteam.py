"""Run the red-team cases (evaluation/redteam.py) with every control on and off.

    uv run python experiments/scripts/redteam.py

Writes experiments/results/redteam/controls.jsonl and controls.md: for each case, whether the attack
worked with the control and without it, and the attack success rate per threat. Needs Docker for
the sandbox and validation cases.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from evaluation.redteam import CASES, run_case

OUT = ROOT / "experiments" / "results" / "redteam"


def rate(rows: list[dict]) -> str:
    return f"{sum(r['attack_succeeded'] for r in rows)}/{len(rows)}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", nargs="*", help="case ids")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    with tempfile.TemporaryDirectory(prefix="locali-redteam-") as tmp:
        for c in CASES:
            if args.only and c.id not in args.only:
                continue
            for defended in (True, False):
                row = run_case(c, defended, Path(tmp) / c.id / ("on" if defended else "off"))
                rows.append(row | {"attack": c.attack, "control": c.control})
                print(f"{c.id:18} control {'on ' if defended else 'off'}  "
                      f"{'ATTACK WORKED' if row['attack_succeeded'] else 'blocked':13}  {row['detail']}")
    (OUT / "controls.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))

    by_threat: dict[str, dict[bool, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for r in rows:
        by_threat[r["threat"]][r["defended"]].append(r)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                            check=False).stdout.strip()
    lines = ["# Red-team: controls on and off", "",
             f"Generated by `experiments/scripts/redteam.py` at commit {commit}. Each attack is run once through",
             "Locali's control and once with that control removed; the cell says whether the attacker got what",
             "they wanted.", "",
             "| Threat | Attacks that worked, control on | Attacks that worked, control off |", "|---|---|---|"]
    lines += [f"| {t} | {rate(v[True])} | {rate(v[False])} |" for t, v in sorted(by_threat.items())]
    lines += ["", "| Case | Attack | Control | On | Off | What happened with the control on |", "|---|---|---|---|---|---|"]
    on = {r["id"]: r for r in rows if r["defended"]}
    off = {r["id"]: r for r in rows if not r["defended"]}
    for case_id, r in on.items():
        mark = {True: "worked", False: "blocked"}
        lines.append(f"| {case_id} | {r['attack']} | {r['control']} | {mark[r['attack_succeeded']]} | "
                     f"{mark[off[case_id]['attack_succeeded']]} | {r['detail'].replace('|', '/')} |")
    (OUT / "controls.md").write_text("\n".join(lines) + "\n")
    print(f"\nwrote {OUT / 'controls.md'}")


if __name__ == "__main__":
    main()
